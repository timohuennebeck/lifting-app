- **환불:** 환불에는 해당 스토어의 약관이 적용됩니다. Apple 또는 Google에 문의해 주십시오.
- **가격 변경:** 활성 구독의 가격은 해당 스토어의 절차에 따라서만 변경될 수 있습니다. 스토어는 사전에 이를 알리고, 필요한 경우 귀하의 동의를 받습니다. 새 가격에 동의하지 않으면 기간 종료 시점에 맞춰 구독을 해지할 수 있습니다.

