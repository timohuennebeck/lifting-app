-- Strength standards for the muscle levels: what an intermediate man of 80 kg reaches on each
-- exercise. For weighted exercises it is the estimated one-rep max ÷ body weight (for bodyweight
-- exercises the added weight counts on top, for assisted ones it's what is left to lift); for
-- exercises with reps only it is the reps, for holds the seconds. Null for exercises that don't
-- make a level (cardio, power and conditioning, very small movements). The app scales it by sex
-- and body weight (^⅔) and places a lift's share of it on the level scale (50 = the standard).

alter table public.exercises add column strength_standard numeric
  check (strength_standard > 0);

